/* MiniStore - MyStore schema and demo data
   Run this script in SQL Server Management Studio / SQL Server Object Explorer.
*/
IF DB_ID(N'MyStore') IS NULL CREATE DATABASE MyStore;
GO
USE MyStore;
GO
IF OBJECT_ID('dbo.OrderDetail','U') IS NOT NULL DROP TABLE dbo.OrderDetail;
IF OBJECT_ID('dbo.[Order]','U') IS NOT NULL DROP TABLE dbo.[Order];
IF OBJECT_ID('dbo.Product','U') IS NOT NULL DROP TABLE dbo.Product;
IF OBJECT_ID('dbo.Category','U') IS NOT NULL DROP TABLE dbo.Category;
IF OBJECT_ID('dbo.Customer','U') IS NOT NULL DROP TABLE dbo.Customer;
IF OBJECT_ID('dbo.[User]','U') IS NOT NULL DROP TABLE dbo.[User];
GO
CREATE TABLE dbo.[User] (
    Username NVARCHAR(255) NOT NULL PRIMARY KEY,
    Password NVARCHAR(100) NOT NULL,
    UserRole NCHAR(1) NOT NULL
);
CREATE TABLE dbo.Customer (
    CustomerID INT IDENTITY(1,1) PRIMARY KEY,
    CustomerName NVARCHAR(200) NOT NULL,
    CustomerPhone NVARCHAR(15) NOT NULL,
    CustomerEmail NVARCHAR(255) NULL,
    CustomerAddress NVARCHAR(500) NULL,
    Username NVARCHAR(255) NOT NULL UNIQUE,
    CONSTRAINT FK_Customer_User FOREIGN KEY (Username) REFERENCES dbo.[User](Username)
);
CREATE TABLE dbo.Category (
    CategoryID INT IDENTITY(1,1) PRIMARY KEY,
    CategoryName NVARCHAR(200) NOT NULL
);
CREATE TABLE dbo.Product (
    ProductID INT IDENTITY(1,1) PRIMARY KEY,
    CategoryID INT NOT NULL,
    ProductName NVARCHAR(200) NOT NULL,
    ProductDescription NVARCHAR(1000) NOT NULL,
    ProductPrice DECIMAL(18,2) NOT NULL,
    ProductImage NVARCHAR(500) NULL,
    CONSTRAINT FK_Product_Category FOREIGN KEY (CategoryID) REFERENCES dbo.Category(CategoryID)
);
CREATE TABLE dbo.[Order] (
    OrderID INT IDENTITY(1,1) PRIMARY KEY,
    CustomerID INT NOT NULL,
    OrderDate DATE NOT NULL,
    TotalAmount DECIMAL(18,2) NOT NULL,
    PaymentStatus NVARCHAR(50) NULL,
    AddressDelivery NVARCHAR(500) NOT NULL,
    DeliveryMethod NVARCHAR(100) NULL,
    PaymentMethod NVARCHAR(100) NULL,
    CONSTRAINT FK_Order_Customer FOREIGN KEY (CustomerID) REFERENCES dbo.Customer(CustomerID)
);
CREATE TABLE dbo.OrderDetail (
    ID INT IDENTITY(1,1) PRIMARY KEY,
    ProductID INT NOT NULL,
    OrderID INT NOT NULL,
    Quantity INT NOT NULL CHECK (Quantity > 0),
    UnitPrice DECIMAL(18,2) NOT NULL,
    TotalPrice AS (Quantity * UnitPrice) PERSISTED,
    CONSTRAINT FK_OrderDetail_Product FOREIGN KEY (ProductID) REFERENCES dbo.Product(ProductID),
    CONSTRAINT FK_OrderDetail_Order FOREIGN KEY (OrderID) REFERENCES dbo.[Order](OrderID)
);
GO
